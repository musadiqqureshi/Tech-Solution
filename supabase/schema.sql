-- 6. EXPERTS  (team members who receive tasks)
-- ============================================================
create table if not exists public.experts (
  id           bigint      generated always as identity primary key,
  user_id      uuid        references auth.users(id) on delete set null,
  name         text        not null,
  title        text        not null default 'Specialist',
  bio          text,
  skills       text[]      not null default '{}',
  accent       text        not null default 'purple',
  show_on_hero boolean     not null default true,
  active       boolean     not null default true,
  avatar_url   text,
  created_at   timestamptz not null default now()
);

-- ============================================================
-- 7. TASKS  (admin assigns to experts, linked to orders)
-- ============================================================
create table if not exists public.tasks (
  id            bigint      generated always as identity primary key,
  expert_id     bigint      not null references public.experts(id) on delete cascade,
  title         text        not null,
  description   text,
  service       text,
  client_alias  text,           -- label shown to expert (hides real client name)
  expert_budget numeric     not null default 0,
  status        text        not null default 'assigned'
                            check (status in (
                              'assigned','in_progress','submitted','approved','completed'
                            )),
  due_date      date,

  -- link to the client order
  order_serial  text,           -- e.g. TSP-202506-0001
  order_id      bigint      references public.orders(id) on delete set null,

  created_at    timestamptz not null default now()
);

-- task_finance: admin-only financial data hidden from experts via RLS
create table if not exists public.task_finance (
  task_id       bigint      primary key references public.tasks(id) on delete cascade,
  client_budget numeric     not null default 0,
  profit        numeric     generated always as (client_budget - (
    select expert_budget from public.tasks t where t.id = task_id
  )) stored,
  order_serial  text,
  created_at    timestamptz not null default now()
);

-- ============================================================
-- 8. MESSAGES  (AI assistant chat history, per user)
-- ============================================================
create table if not exists public.messages (
  id         bigint      generated always as identity primary key,
  user_id    uuid        not null references auth.users(id) on delete cascade,
  role       text        not null check (role in ('user', 'assistant')),
  content    text        not null,
  created_at timestamptz not null default now()
);

-- ============================================================
-- 9. CHAT MESSAGES  (live client ↔ admin real-time chat)
-- ============================================================
create table if not exists public.chat_messages (
  id          bigint      generated always as identity primary key,
  room_id     uuid        not null,  -- equals the client's user_id (one room per client)
  sender_id   uuid        not null references auth.users(id) on delete cascade,
  sender_role text        not null check (sender_role in ('client', 'admin')),
  content     text        not null,
  read_at     timestamptz,           -- null = unread by the other party
  created_at  timestamptz not null default now()
);

create index if not exists chat_messages_room_idx
  on public.chat_messages(room_id, created_at);

-- ============================================================
