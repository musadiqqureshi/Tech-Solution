-- 1. HELPER FUNCTION — is_admin()
-- ============================================================
create or replace function public.is_admin()
returns boolean
language sql stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin'
  );
$$;

-- ============================================================
-- 2. PROFILES  (one row per auth user, auto-created on signup)
-- ============================================================
create table if not exists public.profiles (
  id         uuid        primary key references auth.users(id) on delete cascade,
  name       text        not null default '',
  email      text        not null default '',
  company    text,
  phone      text,
  role       text        not null default 'client'
                         check (role in ('client', 'admin', 'expert')),
  created_at timestamptz not null default now()
);

-- Auto-create profile row whenever a new user signs up
create or replace function public.handle_new_user()
returns trigger language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, email, company, phone, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', ''),
    coalesce(new.email, ''),
    new.raw_user_meta_data->>'company',
    new.raw_user_meta_data->>'phone',
    case when lower(coalesce(new.email, '')) = 'muzzammilkhan7890@gmail.com'
         then 'admin' else 'client' end
  )
  on conflict (id) do update
    set role = case when lower(coalesce(new.email, '')) = 'muzzammilkhan7890@gmail.com'
                    then 'admin' else public.profiles.role end;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Backfill profiles for any EXISTING auth users (signed up before the
-- trigger, or after a reset), then guarantee the owner is an admin.
insert into public.profiles (id, name, email)
select u.id, coalesce(u.raw_user_meta_data->>'name', ''), coalesce(u.email, '')
from auth.users u
on conflict (id) do nothing;

update public.profiles set role = 'admin'
where lower(email) = 'muzzammilkhan7890@gmail.com';

-- ============================================================
-- 3. ORDERS  (client project requests)
-- ============================================================
create table if not exists public.orders (
  id               bigint      generated always as identity primary key,
  user_id          uuid        not null references auth.users(id) on delete cascade,

  -- project basics
  service          text        not null,
  description      text,
  budget           numeric     not null default 0,
  deadline         text,
  priority         text        not null default 'medium'
                               check (priority in ('low', 'medium', 'high')),
  status           text        not null default 'pending'
                               check (status in (
                                 'pending','approved','in_progress',
                                 'delivered','completed','rejected'
                               )),

  -- finance estimates (auto-calculated on insert)
  est_cost         numeric     not null default 0,
  est_profit       numeric     not null default 0,
  breakdown        jsonb,

  -- client-supplied file links
  file_link        text,
  file_link_type   text        check (file_link_type in ('gdrive', 'github')),

  -- delivery
  delivery_type    text        check (delivery_type in ('github', 'gdrive', 'other')),
  delivery_url     text,
  delivered_at     timestamptz,

  -- payment tracking
  payment_status   text        not null default 'unpaid'
                               check (payment_status in ('unpaid', 'paid')),
  paid_at          timestamptz,
  paid_marked_by   text        check (paid_marked_by in ('client', 'admin')),

  -- serial number (auto-generated by trigger: TSP-YYYYMM-XXXX)
  order_serial     text,

  -- optional admin-supplied client details (for manual/offline clients)
  client_name      text,
  client_email     text,
  client_phone     text,
  client_company   text,

  created_at       timestamptz not null default now()
);

-- Serial number generator: TSP-202506-0001
create or replace function public.generate_order_serial(order_id bigint, created timestamptz)
returns text language sql immutable as $$
  select 'TSP-' || to_char(created, 'YYYYMM') || '-' || lpad(order_id::text, 4, '0')
$$;

create or replace function public.set_order_serial()
returns trigger language plpgsql as $$
begin
  new.order_serial := public.generate_order_serial(new.id, new.created_at);
  return new;
end;
$$;

drop trigger if exists trg_set_order_serial on public.orders;
create trigger trg_set_order_serial
  before insert on public.orders
  for each row execute function public.set_order_serial();

-- Backfill any existing rows that don't yet have a serial
update public.orders
set order_serial = public.generate_order_serial(id, created_at)
where order_serial is null;

