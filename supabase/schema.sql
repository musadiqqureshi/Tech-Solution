-- Experts can only see their own tasks
create policy "tasks expert read" on public.tasks
  for select using (
    public.is_admin()
    or exists (
      select 1 from public.experts e
      where e.id = tasks.expert_id and e.user_id = auth.uid()
    )
  );

create policy "tasks admin all" on public.tasks
  for all using (public.is_admin()) with check (public.is_admin());

create policy "tasks expert update" on public.tasks
  for update using (
    exists (
      select 1 from public.experts e
      where e.id = tasks.expert_id and e.user_id = auth.uid()
    )
  );

